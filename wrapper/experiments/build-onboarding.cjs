// Compile reviewed HTML into an isolated, offline production view. No preview scripts ship.
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('../node_modules/jsdom');
const base = path.resolve(__dirname, '..');
function read(name) {
  const dom = new JSDOM(fs.readFileSync(path.join(base, 'prototype', name), 'utf8'));
  const d = dom.window.document;
  d.querySelectorAll('.status,.home').forEach(e => e.remove());
  d.querySelectorAll('[data-proof-status],[data-rating-status]').forEach(e=>{e.removeAttribute('data-proof-status');e.removeAttribute('data-rating-status');});
  d.querySelectorAll('.review-stars').forEach(e=>e.setAttribute('aria-label','Five stars'));
  const css = [...d.querySelectorAll('style')].map(e => e.textContent).join('\n');
  const result = {css, html: (d.querySelector('.icons')?.outerHTML || '') + d.querySelector('.phone').outerHTML};
  dom.window.close(); return result;
}
const views = {paywall: read('paywall-yearly-inbox-preview.html'), progress: read('onboarding-progress-preview.html'), gift: read('onboarding-gift.html'), offer: read('onboarding-special-offer.html')};
const out = '// Generated by experiments/build-onboarding.cjs. Do not edit.\nwindow.KonvoOnboardingViews = ' + JSON.stringify(views) + ';\n';
fs.writeFileSync(path.join(base, 'src-tauri/src/onboarding-views.js'), out);
